//ANCHOR Handles AJAX request to fetch currency data and recalculate costs.
function topic_tree_fetch_currency_data() {
    if (!check_ajax_referer('topic_tree_seo_nonce', 'nonce', false)) {
        wp_send_json_error('Invalid nonce');
        return;
    }
    if (!current_user_can('manage_options')) {
        wp_send_json_error('Unauthorized');
        return;
    }

    // Recalculate total cost based on cached token counts
    $posts = topic_tree_get_all_content('post', false);
    $pages = topic_tree_get_all_content('page', false);
    $total_input_tokens = 0;
    $total_output_tokens = 0;

    $cost_per_input_token_usd = 0.03 / 1000;
    $cost_per_output_token_usd = 0.06 / 1000;

    // Overall summary tokens
    $overall_cache_key = 'tt_overall_summary_' . md5(implode('', array_map(function ($p) {
        return ($p->post_title ?: '') . ($p->post_content ?: '');
    }, array_merge($posts, $pages))));
    $overall_tokens = get_transient($overall_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
    $total_input_tokens += $overall_tokens['input'];
    $total_output_tokens += $overall_tokens['output'];
    error_log("Overall tokens: " . print_r($overall_tokens, true));

    // Individual post/page summary tokens
    foreach (array_merge($posts, $pages) as $p) {
        $summary_cache_key = 'tt_summary_' . md5($p->post_content ?: '');
        $tokens_data = get_transient($summary_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
        $total_input_tokens += (int) ($tokens_data['input'] ?? 0);
        $total_output_tokens += (int) ($tokens_data['output'] ?? 0);
        error_log("Tokens for post {$p->ID}: " . print_r($tokens_data, true));
    }

    // Grouped content tokens (if merged)
    $merge_content = get_option('topic_tree_merge_content', false);
    if ($merge_content && count($posts) + count($pages) > 0) {
        $all_summaries = array_merge(
            array_map(function ($p) { return ['id' => $p->ID, 'summary' => get_transient('tt_summary_' . md5($p->post_content ?: ''))]; }, $posts),
            array_map(function ($p) { return ['id' => $p->ID, 'summary' => get_transient('tt_summary_' . md5($p->post_content ?: ''))]; }, $pages)
        );
        $group_cache_key = 'tt_grouped_' . md5(json_encode($all_summaries) . 'content');
        $tokens_data = get_transient($group_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
        $total_input_tokens += (int) ($tokens_data['input'] ?? 0);
        $total_output_tokens += (int) ($tokens_data['output'] ?? 0);
        error_log("Grouped tokens in fetch: " . print_r($tokens_data, true));
    }

    $input_cost_usd = $total_input_tokens * $cost_per_input_token_usd;
    $output_cost_usd = $total_output_tokens * $cost_per_output_token_usd;
    $total_cost_usd = $input_cost_usd + $output_cost_usd;
    error_log("Total cost in fetch: Input Tokens=$total_input_tokens, Output Tokens=$total_output_tokens, Cost=$total_cost_usd");

    $currencies = ['USD', 'CAD', 'EUR', 'GBP', 'AUD', 'JPY', 'INR'];
    $cache_hits = 0;
    $exchange_rates = topic_tree_get_exchange_rates($total_cost_usd, $currencies, $cache_hits);

    wp_send_json_success([
        'exchangeRates' => $exchange_rates,
        'totalCostUsd' => $total_cost_usd
    ]);
}
add_action('wp_ajax_topic_tree_fetch_currency', 'topic_tree_fetch_currency_data');