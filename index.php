    }
    $output .= '</ul>';
    return $output;
}

//ANCHOR Renders individual post or page summaries in a list format.
function topic_tree_fetch_seo_suggestions() {
    check_ajax_referer('topic_tree_seo_nonce', 'nonce');

    if (!current_user_can('manage_options')) {
        wp_send_json_error('Unauthorized access');
    }

    $item = isset($_POST['item']) ? json_decode(stripslashes($_POST['item']), true) : null;
    if (!$item || !is_array($item)) {
        wp_send_json_error('Invalid item data');
    }

    $item = array_map('sanitize_text_field', $item); // Sanitize input

    $suggestions = topic_tree_generate_seo_suggestions($item);
    if (!is_array($suggestions) || empty($suggestions)) {
        wp_send_json_error('Failed to generate SEO suggestions');
    }

    wp_send_json_success($suggestions);
}
