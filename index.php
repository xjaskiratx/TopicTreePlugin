//ANCHOR - Retrieves the latest modified time of published posts or pages.
function topic_tree_get_latest_modified_time() {
    $query = new WP_Query([
        'post_type' => ['post', 'page'],
        'post_status' => 'publish',
        'posts_per_page' => 1,
        'orderby' => 'modified',
        'order' => 'DESC'
    ]);
    $latest = $query->have_posts() ? get_the_modified_time('U', $query->posts[0]) : 0;
    wp_reset_postdata();
    return $latest;
}

//ANCHOR - Invalidates cache when a post or page is updated.
function topic_tree_invalidate_on_post_update($post_id, $post, $update) {
    if ($post->post_status === 'publish' && in_array($post->post_type, ['post', 'page'])) {
        delete_transient('tt_last_modified');
    }
}
add_action('save_post', 'topic_tree_invalidate_on_post_update', 10, 3);

/**
 * Calculate token count for a post/page based on its content.
 * @param int    $post_id The ID of the post/page.
 * @param string $content The content to calculate tokens for.
 * @return int The calculated token count.
 */

//ANCHOR - Estimates token count for content and saves it to post meta.
 function topic_tree_calculate_token_count($post_id, $content) {
    if (empty($content)) {
        return 0; // Fallback if content is empty
    }
    // Rough estimate: 1 token ≈ 4 characters
    $token_count = ceil(strlen($content) / 4);
    // Save the token count to post meta
    update_post_meta($post_id, 'token_count', $token_count);
    return $token_count;
}

//ANCHOR - Displays the Topic Tree analysis page with summaries, groups, and stats.
function topic_tree_display_analysis()
{
    if (!current_user_can('manage_options')) {
        wp_die('Unauthorized access');
    }

    $start_time = microtime(true);
    $merge_content = get_option('topic_tree_merge_content', false);
    $force_refresh = isset($_GET['force_refresh']) && $_GET['force_refresh'] === 'true';

    $last_modified = get_transient('tt_last_modified');
    $current_modified = topic_tree_get_latest_modified_time();
    if ($last_modified === false || $current_modified > $last_modified || $force_refresh) {
        delete_transient('tt_content_post');
        delete_transient('tt_content_page');
        global $wpdb;
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_summary_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_grouped_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_overall_summary_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_html_grouped_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_seo_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_hybrid_insights_%'");
        $wpdb->query("DELETE FROM {$wpdb->options} WHERE option_name LIKE '_transient_tt_keywords_%'");
        $wpdb->query("DELETE FROM {$wpdb->postmeta} WHERE meta_key = 'token_count'");
        set_transient('tt_last_modified', $current_modified, WEEK_IN_SECONDS);
        $force_refresh = true;
    }

    $all_summaries = topic_tree_summarize_content($force_refresh);

    if (!is_array($all_summaries)) {
        wp_die('Error: Could not retrieve content summaries.');
    }

    $total_posts = count(array_filter($all_summaries, fn($item) => $item['type'] === 'post'));
    $total_pages = count(array_filter($all_summaries, fn($item) => $item['type'] === 'page'));
    $total_items = $total_posts + $total_pages;
    $total_api_calls = 0;
    $total_input_tokens = 0;
    $total_output_tokens = 0;
    $total_tokens = 0;
    $cache_hits = 0;
    $cache_opportunities = $total_items + 1;
    if ($merge_content && $total_items > 0) {
        $cache_opportunities += 1;
    }

    $cost_per_input_token_usd = 0.03 / 1000;
    $cost_per_output_token_usd = 0.06 / 1000;

    foreach ($all_summaries as &$item) {
        $summary_cache_key = 'tt_summary_' . md5(get_post_field('post_content', $item['id']));
        $tokens_data = get_transient($summary_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
        $item['tokens'] = $tokens_data;
        $total_input_tokens += (int) ($tokens_data['input'] ?? 0);
        $total_output_tokens += (int) ($tokens_data['output'] ?? 0);
        $total_tokens += (int) ($tokens_data['total'] ?? 0);
        if (get_transient($summary_cache_key) !== false) {
            $cache_hits++;
        } else {
            $total_api_calls++;
        }
    }
    unset($item);

    $posts = array_filter($all_summaries, fn($item) => $item['type'] === 'post');
    $pages = array_filter($all_summaries, fn($item) => $item['type'] === 'page');
    $overall_summary = topic_tree_generate_overall_summary(
        array_map(fn($item) => (object) ['post_title' => $item['title'], 'post_content' => $item['summary']], $posts),
        array_map(fn($item) => (object) ['post_title' => $item['title'], 'post_content' => $item['summary']], $pages),
        $force_refresh
    );
    $overall_cache_key = 'tt_overall_summary_' . md5(implode('', array_map(function ($item) {
        return ($item['title'] ?: '') . ($item['summary'] ?: '');
    }, $all_summaries)));
    $overall_tokens = get_transient($overall_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
    $total_input_tokens += (int) ($overall_tokens['input'] ?? 0);
    $total_output_tokens += (int) ($overall_tokens['output'] ?? 0);
    $total_tokens += (int) ($overall_tokens['total'] ?? 0);
    if (get_transient($overall_cache_key) !== false) {
        $cache_hits++;
    } else {
        $total_api_calls++;
    }

    $grouped_content = null;
    if ($merge_content && $total_items > 0) {
        $group_cache_key = 'tt_grouped_' . md5(json_encode($all_summaries) . 'content');
        if ($force_refresh) {
            delete_transient($group_cache_key);
            delete_transient($group_cache_key . '_tokens');
        }
        $cached_grouped = get_transient($group_cache_key);
        if ($cached_grouped !== false) {
            $cache_hits++;
            $grouped_content = $cached_grouped;
        } else {
            $grouped_content = topic_tree_extract_and_group_topics($all_summaries, 'content', $force_refresh);
            error_log("Set grouped content: " . (is_string($grouped_content) ? 'Success' : 'Failed'));
            $total_api_calls++;
        }
        $group_tokens = get_transient($group_cache_key . '_tokens') ?: ['input' => 0, 'output' => 0, 'total' => 0];
        $total_input_tokens += (int) ($group_tokens['input'] ?? 0);
        $total_output_tokens += (int) ($group_tokens['output'] ?? 0);
        $total_tokens += (int) ($group_tokens['total'] ?? 0);
    }

    $input_cost_usd = $total_input_tokens * $cost_per_input_token_usd;
    $output_cost_usd = $total_output_tokens * $cost_per_output_token_usd;
    global $total_cost_usd, $exchange_rates;
    $total_cost_usd = $input_cost_usd + $output_cost_usd;
    error_log("Total cost in display: Input Tokens=$total_input_tokens, Output Tokens=$total_output_tokens, Total=$total_tokens, Cost=$total_cost_usd");

    $currencies = ['USD', 'CAD', 'EUR', 'GBP', 'AUD', 'JPY', 'INR'];
    $exchange_rates = topic_tree_get_exchange_rates($total_cost_usd, $currencies, $cache_hits);

    $site_name = get_bloginfo('name');
    $recent_query = new WP_Query([
        'post_type' => ['post', 'page'],
        'post_status' => 'publish',
        'posts_per_page' => 1,
        'orderby' => 'modified',
        'order' => 'DESC',
    ]);
    $recent_item = $recent_query->have_posts() ? $recent_query->posts[0] : null;
    $recent_title = $recent_item ? $recent_item->post_title : 'None';
    $recent_date = $recent_item ? get_the_modified_date('F j, Y', $recent_item->ID) : 'N/A';
    $recent_url = $recent_item ? get_permalink($recent_item->ID) : '#';
    if ($recent_url && strpos($recent_url, 'http') !== 0) {
        $recent_url = home_url($recent_url);
    }
    wp_reset_postdata();

    $cache_hit_ratio = ($cache_opportunities > 0) ? ($cache_hits / $cache_opportunities) * 100 : 0;

    ?>
    <div class="wrap topic-tree">
        <button id="sidebar-toggle" class="sidebar-toggle-btn" style="display: none;">☰</button>
        <div class="left-panel">
            <div class="sidebar" id="sidebar">
                <button id="sidebar-close" class="sidebar-close-btn">×</button>
                <h2>Site Info</h2>
                <ul>
                    <li><strong>Site Name:</strong> <?php echo esc_html($site_name); ?></li>
                    <li><strong>Total Published Posts:</strong> <?php echo esc_html($total_posts); ?></li>
                    <li><strong>Total Published Pages:</strong> <?php echo esc_html($total_pages); ?></li>
                    <li><strong>Most Recently Edited:</strong> <a href="<?php echo esc_url($recent_url); ?>" target="_blank"
                            rel="noopener noreferrer"><?php echo esc_html($recent_title); ?></a>
                        <em>(<?php echo esc_html($recent_date); ?>)</em></li>
                    <li><strong>Total API Calls:</strong> <?php echo esc_html($total_api_calls); ?></li>
                    <li><strong>Cache Hit Ratio:</strong> <?php echo esc_html(number_format($cache_hit_ratio, 1)); ?>%</li>
                    <li><strong>Total Input Tokens:</strong> <?php echo esc_html(number_format($total_input_tokens)); ?></li>
                    <li><strong>Total Output Tokens:</strong> <?php echo esc_html(number_format($total_output_tokens)); ?></li>
                    <li><strong>Total Tokens Used:</strong> <?php echo esc_html(number_format($total_tokens)); ?></li>
                    <li>
                        <strong>Total Cost:</strong>
                        <select id="currency-selector">
                            <?php foreach ($currencies as $currency): ?>
                                <option value="<?php echo esc_attr($currency); ?>" <?php echo $currency === 'USD' ? 'selected' : ''; ?>>
                                    <?php echo esc_html($currency); ?>
                                </option>
                            <?php endforeach; ?>
                        </select>
                        <span id="total-cost-display">Loading...</span>
                    </li>
                </ul>
            </div>
            <div class="group-index-container" id="group-index-container">
                <h2><?php echo $merge_content ? 'Group Index' : 'All Content'; ?></h2>
                <?php
                if ($merge_content && $total_items > 0 && $grouped_content) {
                    // Grouped mode: Display group links
                    $decoded_groups = json_decode($grouped_content, true);
                    if ($decoded_groups && !empty($decoded_groups)) {
                        echo '<ul>';
                        foreach (array_keys($decoded_groups) as $group) {
                            $group_id = 'group-' . sanitize_title($group);
                            echo '<li><a href="#' . esc_attr($group_id) . '">' . esc_html($group) . '</a></li>';
                        }
                        echo '</ul>';
                    } else {
                        echo '<p>No groups available.</p>';
                    }
                } else {
                    // Flat list mode: Display links to all individual pages and posts
                    echo '<ul>';
                    $has_items = false;

                    // List all pages
                    if (!empty($pages)) {
                        foreach ($pages as $page) {
                            $title = isset($page['title']) ? $page['title'] : 'Untitled';
                            $post_id = isset($page['id']) ? $page['id'] : sanitize_title($title);
                            echo '<li><a href="#page-' . esc_attr($post_id) . '">[Page] ' . esc_html($title) . '</a></li>';
                            $has_items = true;
                        }
                    }

                    // List all posts
                    if (!empty($posts)) {
                        foreach ($posts as $post) {
                            $title = isset($post['title']) ? $post['title'] : 'Untitled';
                            $post_id = isset($post['id']) ? $post['id'] : sanitize_title($title);
                            echo '<li><a href="#post-' . esc_attr($post_id) . '">[Post] ' . esc_html($title) . '</a></li>';
                            $has_items = true;
                        }
                    }

                    // If no items, show a message
                    if (!$has_items) {
                        echo '<li>No content available.</li>';
                    }

                    echo '</ul>';
                }
                ?>
            </div>
        </div>
        <div class="main-content">
            <h1>Topic Tree Analysis</h1>
            <p class="description">Generated by GPT-4. <a
                    href="<?php echo esc_url(admin_url('admin.php?page=topic-tree-settings')); ?>">Adjust settings</a>.
                <a href="<?php echo esc_url(add_query_arg('force_refresh', 'true')); ?>">Force Refresh Token Counts</a>
            </p>

            <div class="section overall-summary">
                <h2>Overall Website Summary</h2>
                <p><?php echo esc_html($overall_summary); ?></p>
            </div>

            <?php if ($merge_content && $total_items > 0) { ?>
                <div class="section grouped-content">
                    <h2>Grouped Content (<?php echo esc_html($total_items); ?> items)</h2>
                    <?php
                    try {
                        echo topic_tree_render_grouped_content($grouped_content, $total_items);
                    } catch (Exception $e) {
                        echo '<p>Error: Failed to render grouped content.</p>';
                    }
                    ?>
                </div>
            <?php } else { ?>
                <div class="section pages-summary">
                    <h2>Pages (<?php echo esc_html($total_pages); ?>)</h2>
                    <?php echo topic_tree_render_summaries($pages, 'page'); ?>
                </div>
                <div class="section posts-summary">
                    <h2>Posts (<?php echo esc_html($total_posts); ?>)</h2>
                    <?php echo topic_tree_render_summaries($posts, 'post'); ?>
                </div>
            <?php } ?>

            <div class="keyword-analysis-wrap">
                <button id="analyze-keywords-btn" class="button button-primary">Analyze Keywords</button>
                <div id="keyword-analysis-output" style="display: none; margin-top: 20px; position: relative;">
                    <span id="keyword-analysis-close" class="keyword-analysis-close-btn">×</span>
                    <h2>Keyword Analysis</h2>
                    <?php foreach ($all_summaries as $item) { ?>
                        <div class="keyword-item">
                            <h3><?php echo esc_html($item['title']); ?> (<?php echo $item['type']; ?>)</h3>
                            <?php
                            // Skip analysis if content is too short (less than 10 words)
                            $word_count = $item['total_words'] ?? 0;
                            if ($word_count < 10) {
                                echo '<p>Content is too short for keyword analysis (minimum 10 words required).</p>';
                                continue;
                            }

                            $keywords = $item['keywords'] ?? [];
                            if (empty($keywords)) {
                                echo '<p>No significant keywords found (minimum 2 occurrences required).</p>';
                                continue;
                            }
                            ?>
                            <table class="wp-list-table widefat striped">
                                <thead>
                                    <tr>
                                        <th scope="col">Keyword</th>
                                        <th scope="col">Occurrences</th>
                                        <th scope="col">Density</th>
                                    </tr>
                                </thead>
                                <tbody>
                                    <?php
                                    // Sort keywords by count and density
                                    uasort($keywords, function($a, $b) {
                                        if ($a['count'] === $b['count']) {
                                            return $b['density'] <=> $a['density'];
                                        }
                                        return $b['count'] <=> $a['count'];
                                    });

                                    foreach ($keywords as $word => $data) {
                                        $density = $data['density'];
                                        $formatted_density = number_format($density, 1);

                                        // Determine row color based on density
                                        $row_style = '';
                                        if ($density >= 1 && $density <= 3) {
                                            // Ideal range: green
                                            $row_style = 'background-color: rgba(46, 204, 113, 0.2);';
                                        } elseif (($density >= 0.5 && $density < 1) || ($density > 3 && $density <= 3.5)) {
                                            // Within 0.5% of limits: yellow
                                            $row_style = 'background-color: rgba(241, 196, 15, 0.2);';
                                        } elseif ($density < 0.5) {
                                            // Too low: orange
                                            $row_style = 'background-color: rgba(243, 156, 18, 0.2);';
                                        } elseif ($density > 3.5) {
                                            // Too high: red
                                            $row_style = 'background-color: rgba(214, 54, 56, 0.2);';
                                        }
                                        ?>
                                        <tr style="<?php echo esc_attr($row_style); ?>">
                                            <td><?php echo esc_html($word); ?></td>
                                            <td><?php echo esc_html($data['count']); ?></td>
                                            <td><?php echo esc_html($formatted_density); ?>%</td>
                                        </tr>
                                        <?php
                                    }
                                    ?>
                                </tbody>
                            </table>
                            <?php
                            // High-density warning
                            $max_density = max(array_column($keywords, 'density'));
                            if ($max_density > 3) {
                                ?>
                                <p class="keyword-note" style="color: #d63638;">High density detected (<?php echo esc_html($max_density); ?>%)—check for over-optimization. Ideal density is 1-3%.</p>
                                <?php
                            }
                            ?>
                        </div>
                    <?php } ?>
                </div>
            </div>
        </div>
    </div>
    <?php
    echo "<!-- Rendered: " . (microtime(true) - $start_time) . "s -->";
}
