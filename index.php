        $output .= '<button class="analyze-btn" data-item="' . $item_json . '">Analyze</button> ';
        $output .= '<a href="' . esc_url($edit_url) . '" class="edit-btn" target="_blank" rel="noopener noreferrer">Edit</a> ';
