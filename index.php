//ANCHOR - Fetches exchange rates for cost display, caching results for a day.
function topic_tree_get_exchange_rates($total_cost_usd, $currencies, &$cache_hits)
{
    $cache_key = 'tt_exchange_rates';
    $cached_rates = get_transient($cache_key);

    if ($cached_rates !== false) {
        $cache_hits++;
        return $cached_rates;
    }

    $api_url = 'https://v6.exchangerate-api.com/v6/015ced6f5ce3a1e42a6d2d54/latest/USD';
    $response = wp_remote_get($api_url, ['timeout' => 10]);

    if (is_wp_error($response)) {
        return topic_tree_fallback_exchange_rates($total_cost_usd, $currencies);
    }

    $body = json_decode(wp_remote_retrieve_body($response), true);
    if (!isset($body['conversion_rates'])) {
        return topic_tree_fallback_exchange_rates($total_cost_usd, $currencies);
    }

    $rates = [];
    $symbols = [
        'USD' => '$',
        'CAD' => 'C$',
        'EUR' => '€',
        'GBP' => '£',
        'AUD' => 'A$',
        'JPY' => '¥',
        'INR' => '₹'
    ];

    foreach ($currencies as $currency) {
        $rate = $body['conversion_rates'][$currency] ?? 1.0;
        $rates[$currency] = [
            'rate' => (float) $rate,
            'symbol' => $symbols[$currency] ?? $currency
        ];
    }

    set_transient($cache_key, $rates, DAY_IN_SECONDS);
    return $rates;
}

