//ANCHOR - Renders grouped content into HTML with pagination and analysis buttons.
function topic_tree_render_grouped_content($grouped_content, $total_items) {
    if (!is_string($grouped_content)) {
        return '<p>Error: Invalid grouped content format.</p>';
    }

    $decoded = json_decode($grouped_content, true);
    if ($decoded === null) {
        return '<p>Error: Invalid JSON format in grouped content.</p>';
    }

    if (empty($decoded)) {
        return '<p>No topics generated.</p>';
    }

    $items_per_page = 10;
    $total_groups = count($decoded);
    $total_pages = ceil($total_groups / $items_per_page);
    $current_page = isset($_GET['tt_page']) ? max(1, intval($_GET['tt_page'])) : 1;
    $offset = ($current_page - 1) * $items_per_page;
    $paged_groups = array_slice($decoded, $offset, $items_per_page, true);

    $cache_key = 'tt_html_grouped_' . md5($grouped_content . $current_page);
    $cached_html = get_transient($cache_key);
    if ($cached_html !== false) {
        return $cached_html;
    }

    $output = '';
    foreach ($paged_groups as $category => $items) {
        if (!is_array($items)) {
            continue;
        }
        $item_count = count($items);
        $item_label = $item_count === 1 ? 'item' : 'items';
        $group_data = json_encode(['category' => $category, 'items' => $items, 'total_items' => $total_items]);
        $toggle_id = 'group-toggle-' . md5($category);
        $group_id = 'group-' . sanitize_title($category);

        $insights = "This content outlines the group of {$item_count} post items, constituting a portion of the site content, primarily revolving around the themes of {$category}. For a WordPress developer, this group is crucial as it represents a significant portion of the site’s content and focuses on contemporary design trends.";

        $output .= '<div class="group-card" id="' . esc_attr($group_id) . '">';
        $output .= '<h3>' . esc_html($category) . ' (' . esc_html($item_count) . ' ' . $item_label . ') ';
        $output .= '<button class="group-analyze-btn" data-group="' . esc_attr($group_data) . '">Show Group Info</button> ';
        $output .= '<button class="toggle-group-btn" data-toggle-id="' . esc_attr($toggle_id) . '">Expand All</button></h3>';

        $output .= '<div class="group-analysis">';
        $output .= '<h4>Group Summary & Importance</h4>';
        $output .= '<p>' . nl2br(esc_html($insights)) . '</p>';
        $output .= '</div>';

        $output .= '<ul class="group-content" id="' . esc_attr($toggle_id) . '">';
        foreach ($items as $index => $item) {
            $title = $item['title'] ?? 'Untitled';
            $summary = $item['summary'] ?? 'No summary'; // Use full summary directly
            $date = $item['date'] ?? 'Unknown Date';
            $type = $item['type'] ?? 'unknown';
            $url = $item['url'] ?? '#';
            if ($url !== '#' && strpos($url, 'http') !== 0) {
                $url = home_url($url);
            }
            $post_id = $item['id'] ?? 0;
            $edit_url = admin_url("post.php?post={$post_id}&action=edit");
            $item_json = esc_attr(json_encode($item));
            $tokens_data = $item['tokens'] ?? ['input' => 0, 'output' => 0, 'total' => 0];
            $tokens_data['input'] = (int)($tokens_data['input'] ?? 0);
            $tokens_data['output'] = (int)($tokens_data['output'] ?? 0);
            $tokens_data['total'] = (int)($tokens_data['total'] ?? 0);
            $token_count = $tokens_data['total'];

            // Debug: Log summary length
            error_log("Grouped Item {$post_id} Summary Length: " . strlen($summary) . " chars, Words: " . topic_tree_count_words($summary));

            $output .= '<li style="position: relative;">';
            if ($item['stale']) {
                $output .= '<div class="stale-mark">';
                $output .= 'Stale';
                $output .= '<span class="stale-tooltip">';
                $output .= 'Created over ' . esc_html($item['created_years']) . ' years ago, ';
                $output .= 'last edited ';
                if ($item['last_edited_years'] > 0) {
                    $output .= esc_html($item['last_edited_years']) . ' years';
                } else {
                    $output .= esc_html($item['last_edited_months']) . ' months';
                }
                $output .= ' ago, consider reviewing or refreshing it.';
                $output .= '</span>';
                $output .= '</div>';
            }
            $output .= '<div>';
            $output .= '<strong><a href="' . esc_url($url) . '" class="content-link" target="_blank" rel="noopener noreferrer">' . esc_html($title) . '</a></strong> ';
            $output .= '<button class="analyze-btn" data-item="' . $item_json . '">Analyze</button> ';
            $output .= '<a href="' . esc_url($edit_url) . '" class="edit-btn" target="_blank" rel="noopener noreferrer">Edit</a> ';
            $output .= '(' . esc_html($type) . ')';
            $output .= '</div>';
            $output .= '<div>' . esc_html($summary) . '</div>'; // Full summary, no truncation
            $output .= '<div><em>(' . esc_html($date) . ')</em></div>';
            $output .= '<div class="token-count">Tokens: Input: ' . esc_html(number_format($tokens_data['input'])) . ', Output: ' . esc_html(number_format($tokens_data['output'])) . ', Total: ' . esc_html(number_format($tokens_data['total'])) . '</div>';
            $output .= '<div class="seo-suggestions-inline" data-post-id="' . esc_attr($post_id) . '" style="display: none;"></div>';
            $output .= '</li>';
        }
        $output .= '</ul>';
        $output .= '</div>';
    }

    $output .= '<div class="pagination">';
    if ($current_page > 1) {
        $prev_page = $current_page - 1;
        $output .= '<a href="' . esc_url(add_query_arg('tt_page', $prev_page)) . '" class="pagination-link">Previous</a>';
    }
    $output .= '<span class="pagination-info">Page ' . esc_html($current_page) . ' of ' . esc_html($total_pages) . '</span>';
    if ($current_page < $total_pages) {
        $next_page = $current_page + 1;
        $output .= '<a href="' . esc_url(add_query_arg('tt_page', $next_page)) . '" class="pagination-link">Next</a>';
    }
    $output .= '</div>';

    $output = $output ?: '<p>No valid grouped content to display.</p>';
    set_transient($cache_key, $output, WEEK_IN_SECONDS);
    return $output;
}

